#!/usr/bin/env python3
"""Reference values of the Faddeeva function for the Voigt unit test.

    w(z) = exp(-z^2) erfc(-iz),  z = v + ia,
    H(a, v) = Re w,  L(a, v) = Im w

computed with mpmath at 40 significant digits and written as a C header,
so that the test itself needs no Python. Values below 1e-300 (H for a = 0
far from line center) are written as 0. Regenerate with

    python3 tests/unit/make_voigt_reference.py > tests/unit/voigt_reference.h
"""
import mpmath

mpmath.mp.dps = 40

A = [0.0, 1e-12, 1e-10, 1e-8, 1e-6, 1e-4, 1e-3, 3e-3, 1e-2, 3e-2, 0.1, 0.3, 0.6, 1.0, 1.5,
     2.0, 3.0, 5.0, 10.0, 30.0, 100.0]
V = ([0.25 * i for i in range(25)] +                     # 0 .. 6 in the core
     [6.5, 7.0, 8.0, 10.0, 12.0, 15.0, 20.0, 30.0, 50.0, 100.0, 300.0,
      1e3, 3e3, 1e4])


def faddeeva(a, v):
    z = mpmath.mpc(v, a)
    return mpmath.exp(-z * z) * mpmath.erfc(-1j * z)


def c_double(x):
    """x as a C constant; values below the double range become 0."""
    if abs(x) < 1e-300:
        return "0.0"
    return mpmath.nstr(x, 17, min_fixed=1, max_fixed=0)


def main():
    print("/* Generated by tests/unit/make_voigt_reference.py -- do not edit."
          "\n   Faddeeva function w(v + ia) = H + iL, mpmath at 40 digits. */\n")
    print("#define VOIGT_REF_NA %d" % len(A))
    print("#define VOIGT_REF_NV %d\n" % len(V))
    print("static const double voigt_ref_a[VOIGT_REF_NA] = {")
    print("".join("\t%.17g,\n" % a for a in A), end="")
    print("};\n")
    print("static const double voigt_ref_v[VOIGT_REF_NV] = {")
    print("".join("\t%.17g,\n" % v for v in V), end="")
    print("};\n")
    print("/* {H, L}, index [ia][iv] */")
    print("static const double voigt_ref_w[VOIGT_REF_NA][VOIGT_REF_NV][2] = {")
    for a in A:
        print("\t{")
        for v in V:
            w = faddeeva(a, v)
            print("\t\t{%s, %s}," % (c_double(w.real), c_double(w.imag)))
        print("\t},")
    print("};")


if __name__ == "__main__":
    main()
