static void setup(ChemSystem *cs, int c)
{
	int s, i;

	cs->Nn  = NN;
	cs->Ns  = NS;
	cs->nu  = matrix_double(NS, NN);
	cs->H   = matrix_double(NN, NN);
	cs->lnc = (double *) malloc(NS * sizeof(double));
	cs->n   = (double *) malloc(NS * sizeof(double));
	cs->g   = (double *) malloc(NN * sizeof(double));
	cs->du  = (double *) malloc(NN * sizeof(double));
	cs->ut  = (double *) malloc(NN * sizeof(double));
	cs->sc  = (double *) malloc(NN * sizeof(double));
	for (s = 0; s < NS; s++) {
		cs->lnc[s] = lnc_tab[c][s];
		for (i = 0; i < NN; i++) cs->nu[s][i] = nu_tab[s][i];
	}
}

static void release(ChemSystem *cs)
{
	freeMatrix((void **) cs->nu);
	freeMatrix((void **) cs->H);
	free(cs->lnc);
	free(cs->n);
	free(cs->g);
	free(cs->du);
	free(cs->ut);
	free(cs->sc);
}

/* --- Densities of all species and the largest relative residual of
	   the conservation equations at u --             -------------- */

static double conservation(ChemSystem *cs, int c, const double *u)
{
	int    s, i;
	double sum[NN] = {0.0}, r = 0.0;

	for (s = 0; s < NS; s++) {
		double e = cs->lnc[s];

		for (i = 0; i < NN; i++) e += nu_tab[s][i] * u[i];
		cs->n[s] = (cs->lnc[s] == -HUGE_VAL) ? 0.0 : exp(e);
		for (i = 0; i < NN; i++) sum[i] += nu_tab[s][i] * cs->n[s];
	}
	for (i = 0; i < NN; i++) r = fmax(r, fabs(sum[i] / a_tab[c][i] - 1.0));
	return r;
}

static void test_reference(void)
{
	int        c, s, i, steps;
	double     u[NN], res, step, r, nsol[NS];
	ChemSystem cs;

	for (c = 0; c < NCASE; c++) {
		setup(&cs, c);
		for (i = 0; i < NN; i++) u[i] = log(a_tab[c][i]);
		steps = chemSolve(&cs, a_tab[c], u, 100, 1.0E-12, &res, &step);
		CHECK(steps > 0 && steps <= 30, "T = %g K: %d steps", T_tab[c], steps);
		for (s = 0; s < NS; s++) nsol[s] = cs.n[s];
		r = conservation(&cs, c, u);
		CHECK(r < 1.0E-12, "T = %g K: conservation residual %.3g", T_tab[c], r);
		for (s = 0; s < NS; s++)
			CHECK(nsol[s] == cs.n[s], "T = %g K: returned n(%s) is not that of u", T_tab[c],
				  species_id[s]);
		for (s = 0; s < NS; s++) {
			if (nref_tab[c][s] > 0.0)
				CHECK(cs.n[s] > 0.0, "T = %g K: n(%s) = %g", T_tab[c], species_id[s], cs.n[s]);
			else
				CHECK(cs.n[s] == 0.0, "T = %g K: absent %s has %g", T_tab[c], species_id[s], cs.n[s]);
			if (nref_tab[c][s] > 1.0E-25 * nHtot_tab[c])
				CHECK_CLOSE(cs.n[s], nref_tab[c][s], 1.0E-9, 0.0, "T = %g K, %s", T_tab[c],
							species_id[s]);
		}
		printf("T = %8.1f K: %2d steps, residual %.2e\n", T_tab[c], steps, r);
		release(&cs);
	}
}

static void test_absent(void)
{
	int        c = 1, i, steps, h2o = NS - 1;
	double     u[NN], res, step, r;
	ChemSystem cs;

	setup(&cs, c);
	cs.lnc[h2o] = -HUGE_VAL;
	for (i = 0; i < NN; i++) u[i] = log(a_tab[c][i]);
	steps = chemSolve(&cs, a_tab[c], u, 100, 1.0E-12, &res, &step);
	CHECK(steps > 0, "without H2O: %d steps", steps);
	r = conservation(&cs, c, u);
	CHECK(r < 1.0E-12, "without H2O: conservation residual %.3g", r);
	CHECK(cs.n[h2o] == 0.0, "without H2O: n(H2O) = %g", cs.n[h2o]);
	release(&cs);
}

static void test_not_converged(void)
{
	int        c = 0, i, steps;
	double     u[NN], res = 0.0, step;
	ChemSystem cs;

	setup(&cs, c);
	for (i = 0; i < NN; i++) u[i] = log(a_tab[c][i]);
	steps = chemSolve(&cs, a_tab[c], u, 2, 1.0E-12, &res, &step);
	CHECK(steps == -1, "2 steps at 1000 K: returned %d (residual %.3g)", steps, res);
	release(&cs);
}

