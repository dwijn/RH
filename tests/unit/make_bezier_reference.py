#!/usr/bin/env python3
"""Reference values of the cubic Bezier integration weights for the 1-D
formal-solver unit test.

Over an interval of optical depth dt, with S_u, S_c the source function at
the upwind and central point and C_u, C_c its Bezier control points,

    I_c = eps I_u + alpha S_u + beta S_c + gamma C_c + theta C_u,

    eps   = exp(-dt)
    alpha = (6 - (6 + 6 dt + 3 dt^2 + dt^3) eps) / dt^3
    beta  = (dt^3 - 3 dt^2 + 6 dt - 6 + 6 eps) / dt^3
    gamma = 3 (2 dt - 6 + (6 + 4 dt + dt^2) eps) / dt^3
    theta = 3 (6 - 4 dt + dt^2 - (6 + 2 dt) eps) / dt^3

(de la Cruz Rodriguez & Piskunov 2013), evaluated with mpmath at 60
digits, so that the cancellation at small dt does not matter. Regenerate
with

    python3 tests/unit/make_bezier_reference.py > tests/unit/bezier_reference.h
"""
import mpmath

mpmath.mp.dps = 60

# 1e-8 .. 1e3, rounded to double first so that the weights belong to
# exactly the dt the test passes
DT = [mpmath.mpf(float(mpmath.mpf(10) ** (e / 4))) for e in range(-32, 13)]


def weights(dt):
    eps = mpmath.exp(-dt)
    dt2, dt3 = dt * dt, dt * dt * dt
    alpha = (6 - (6 + 6 * dt + 3 * dt2 + dt3) * eps) / dt3
    beta = (dt3 - 3 * dt2 + 6 * dt - 6 + 6 * eps) / dt3
    gamma = 3 * (2 * dt - 6 + (6 + 4 * dt + dt2) * eps) / dt3
    theta = 3 * (6 - 4 * dt + dt2 - (6 + 2 * dt) * eps) / dt3
    return eps, alpha, beta, gamma, theta


def c(x):
    return "0.0" if abs(x) < 1e-300 else mpmath.nstr(x, 17, min_fixed=1, max_fixed=0)


def main():
    print("/* Generated by tests/unit/make_bezier_reference.py -- do not edit."
          "\n   Cubic Bezier integration weights, mpmath at 60 digits. */\n")
    print("#define BEZIER_REF_N %d\n" % len(DT))
    print("/* {dt, eps, alpha, beta, gamma, theta} */")
    print("static const double bezier_ref[BEZIER_REF_N][6] = {")
    for dt in DT:
        print("\t{%s}," % ", ".join(c(x) for x in (dt,) + weights(dt)))
    print("};")


if __name__ == "__main__":
    main()
